import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import { pathToFileURL } from 'node:url';
process.env.OPEN_WEBSEARCH_QUIET_STARTUP = 'true';
const root = process.cwd();
const out = path.join(root, 'docs/security-code-audit-2026-10-10');
const fromBuild = name => import(pathToFileURL(path.join(root, 'build', name)));
const { RESOURCE_LIMITS } = await fromBuild('utils/resourceLimits.js');
const { SessionLimiter } = await fromBuild('adapters/http/sessionLimiter.js');
const { createSearchService } = await fromBuild('core/search/searchService.js');
const { createArticleFetchService } = await fromBuild('core/fetch/fetchServices.js');
const { buildAxiosRequestOptions, requestWithSafeRedirects, __setAxiosRequestForTests } = await fromBuild('utils/httpRequest.js');
const { __setDnsLookupForTests } = await fromBuild('utils/urlSafety.js');
const results = [];
let now = 0, expired = 0;
const limiter = new SessionLimiter(undefined, undefined, () => now);
const sessions = Array.from({ length: RESOURCE_LIMITS.maxMcpSessions }, () => limiter.acquire(() => expired++));
assert(sessions.every(Boolean)); assert.equal(limiter.acquire(() => {}), null);
now = RESOURCE_LIMITS.sessionIdleTimeoutMs - 1; limiter.sweep(); assert.equal(expired, 0);
now++; limiter.sweep(); assert.equal(expired, RESOURCE_LIMITS.maxMcpSessions);
results.push({ test: 'current-session-ttl-boundary', maximum: sessions.length, idleTimeoutMs: now, expired });
let calls = 0;
const search = createSearchService({ bing: async () => { calls++; return []; }, exa: async () => { calls++; return []; } });
await search.execute({ query: 'audit', engines: ['BING', 'bing', 'exa'], limit: 1 }); assert.equal(calls, 1);
await assert.rejects(search.execute({ query: 'audit', engines: Array(256).fill('bing'), limit: 1 }), /engines must/);
await assert.rejects(search.execute({ query: 'x'.repeat(2049), engines: ['bing'], limit: 1 }), /Query must/);
results.push({ test: 'dedup-zero-budget-and-input-bounds', calls, passed: true });
let releaseSearch;
const searchGate = new Promise(resolve => { releaseSearch = resolve; });
const busy = createSearchService({ bing: async () => { await searchGate; return []; } });
const jobs = Array.from({ length: RESOURCE_LIMITS.maxConcurrentSearches }, () => busy.execute({ query: 'audit', engines: ['bing'], limit: 1 }));
await assert.rejects(busy.execute({ query: 'audit', engines: ['bing'], limit: 1 }), { code: 'resource_limit' });
releaseSearch(); await Promise.all(jobs);
let releaseFetch;
const fetchGate = new Promise(resolve => { releaseFetch = resolve; });
const article = createArticleFetchService('juejin', async () => { await fetchGate; return { content: 'fixture' }; });
const fetchJobs = Array.from({ length: RESOURCE_LIMITS.maxConcurrentFetches }, () => article.execute({ url: 'https://juejin.cn/post/1' }));
await assert.rejects(article.execute({ url: 'https://juejin.cn/post/1' }), { code: 'resource_limit' });
releaseFetch(); await Promise.all(fetchJobs);
results.push({ test: 'search-and-fetch-concurrency', searches: jobs.length, fetches: fetchJobs.length, passed: true });
const options = buildAxiosRequestOptions({ timeout: 0, maxContentLength: -1, maxBodyLength: 0 });
assert.equal(options.timeout, RESOURCE_LIMITS.requestTimeoutMs);
assert.equal(options.maxContentLength, RESOURCE_LIMITS.maxResponseBytes);
assert.equal(options.maxBodyLength, RESOURCE_LIMITS.maxResponseBytes);
__setDnsLookupForTests(async () => [{ address: '93.184.216.34' }]);
__setAxiosRequestForTests(async () => new Promise(() => {}));
try {
  const started = Date.now();
  await assert.rejects(requestWithSafeRedirects('GET', 'http://audit-timeout.test/', { timeout: 30 }), /timed out/);
  results.push({ test: 'http-absolute-timeout', requestedMs: 30, actualMs: Date.now() - started, passed: true });
} finally { __setDnsLookupForTests(); __setAxiosRequestForTests(); }
fs.writeFileSync(path.join(out, 'resource-probes.json'), JSON.stringify({ limits: RESOURCE_LIMITS, results }, null, 2));
for (const item of results) console.log(JSON.stringify(item));
